def detect_language(text: str) -> LanguageType:
    if not text or not text.strip():
        return "English"

    # 1. Check Urdu script first
    if re.search(r"[\u0600-\u06FF]", text):
        return "Urdu"

    # 2. Check Roman Urdu markers with word count + hit ratio
    words = re.findall(r"[a-zA-Z]+", text.lower())
    total_words = len(words)
    if total_words > 0:
        hits = sum(1 for w in words if w in ROMAN_URDU_MARKERS)
        ratio = hits / total_words

        if total_words <= 15 and hits >= 2 and ratio >= 0.25:
            return "Roman Urdu"
        if total_words > 15 and hits >= 3 and ratio >= 0.12:
            return "Roman Urdu"

    # 3. Fallback statistical check for Urdu
    try:
        if detect(text) == "ur":
            return "Urdu"
    except Exception:
        pass

    return "English"